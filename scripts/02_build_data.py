"""Stage 2: clean the raw cache into panels and write the data quality report."""
import _bootstrap  # noqa: F401

from src.config import data_dir, load_config, parse_args, reports_dir
from src.data.clean import build_panels
from src.data.panels import holdout_start, save_panels
from src.report.io import save_json, save_table, to_markdown
from src.report.plots import plot_survivorship


def main() -> None:
    cfg = load_config(parse_args(__doc__).config)
    panels, summary, details = build_panels(cfg, data_dir(cfg))
    save_panels(panels, cfg)

    start = holdout_start(panels.dates, cfg["split"]["holdout_months"])
    summary["holdout_start"] = str(start.date())
    summary["research_end"] = str(panels.dates[panels.dates < start][-1].date())
    summary["synthetic"] = bool(cfg["data"].get("synthetic"))
    save_json(summary, "data_quality", cfg)
    for name, table in details.items():
        save_table(table, name, cfg, index=False)
    plot_survivorship(details["survivorship_by_year"], reports_dir(cfg) / "figures" / "fig1_survivorship.png")

    lines = ["# Data report", "", "Generated by scripts/02_build_data.py. Do not edit by hand.", ""]
    if summary["synthetic"]:
        lines += ["**SYNTHETIC DATA. Not market data, not a research result.**", ""]
    lines += ["## Summary", "", "| item | value |", "|---|---|"]
    lines += [f"| {k} | {v:,.1f} |" if isinstance(v, float) else f"| {k} | {v} |" for k, v in summary.items()]
    lines += ["", "## Survivorship by year", "",
              "members_no_data = index members in that year for which yfinance has no prices.", "",
              to_markdown(details["survivorship_by_year"], fmt={"year": "{:d}", "members_in_year": "{:d}",
                          "members_no_data": "{:d}"}, default="{:.1f}", index=False), ""]
    lines += ["## Extreme one-day returns", "", f"{len(details['extreme_returns'])} events. "
              "Full list: tables/extreme_returns.csv", "",
              "## Membership inconsistencies", "",
              f"{len(details['membership_inconsistencies'])} events in the Wikipedia change log do not fit the "
              "reconstructed set. Full list: tables/membership_inconsistencies.csv", ""]
    (reports_dir(cfg) / "data_report.md").write_text("\n".join(lines))
    for k, v in summary.items():
        print(f"{k:40s} {v}")


if __name__ == "__main__":
    main()
