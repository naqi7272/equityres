"""Build reports/writeup.md and the README result table from saved result files.

Every number in the writeup is read from reports/tables. Nothing is typed by
hand, and the sentences that state conclusions are chosen by the code from
the numbers.
"""
from __future__ import annotations

import pandas as pd

from src.config import ROOT, reports_dir
from src.data.panels import holdout_access_count
from src.report.io import has_result, load_json, load_table, to_markdown
from src.timing import ENTRY_LAG

PCT = "{:.1%}"


def _headline_table(cfg: dict) -> str:
    """Research-set CV versus holdout for the frozen configuration."""
    res = load_json("combination_results", cfg)
    cv = load_table("cv_results", cfg).loc[res["selection"]["chosen_hash"]]
    cols = {"gross_sharpe": "Sharpe, gross", "net_sharpe": "Sharpe, net", "net_ann_return": "Ann. return, net",
            "net_ann_vol": "Ann. vol", "net_max_drawdown": "Max drawdown", "daily_turnover": "Daily turnover",
            "break_even_bps": "Break-even cost (bps/side)", "net_market_beta": "Market beta", "n_days": "Days"}
    table = pd.DataFrame({"Research set (purged CV)": cv[list(cols)]})
    if has_result("holdout_results.json", cfg):
        table["Holdout (single run)"] = pd.Series(load_json("holdout_results", cfg)["summary"])[list(cols)]
    table.index = [cols[c] for c in table.index]

    def cell(name: str, v: float) -> str:
        if name in ("Ann. return, net", "Ann. vol", "Max drawdown", "Daily turnover"):
            return PCT.format(v)
        return f"{v:.0f}" if name == "Days" else (f"{v:.1f}" if "bps" in name else f"{v:.2f}")

    out = table.apply(lambda col: [cell(n, float(v)) for n, v in col.items()])
    out.index.name = "Metric"
    return to_markdown(out)


def build_writeup(cfg: dict) -> None:
    rd = reports_dir(cfg)
    dq = load_json("data_quality", cfg)
    surv = load_table("survivorship_by_year", cfg, index_col=None)
    meta = load_json("signal_eval_meta", cfg)
    sig = load_table("signal_summary", cfg)
    res = load_json("combination_results", cfg)
    sel, st = res["selection"], res["stats"]
    cv = load_table("cv_results", cfg)
    cpcv = load_table("cpcv_summary", cfg)
    costs = load_table("cost_sensitivity", cfg)
    robust = load_table("robustness_horizons", cfg)
    by_year = load_table("cv_sharpe_by_year", cfg)
    holdout = load_json("holdout_results", cfg) if has_result("holdout_results.json", cfg) else None
    h, cost, val = cfg["label"]["horizon"], cfg["costs"]["base_bps"], cfg["validation"]
    chosen = cv.loc[sel["chosen_hash"]]
    fam = sel["chosen_family"]
    L: list[str] = []
    add = L.append

    add("# Do simple price and volume signals survive leak-free validation?")
    add("")
    add("*Generated by `src/report/writeup.py` from the files in `reports/tables`. Every number comes from the code.*")
    if dq.get("synthetic"):
        add("")
        add("> **SYNTHETIC DATA.** This file was produced by the smoke test. It is not a research result.")
    add("")
    add("## 1. Question")
    add("")
    add("Do eight simple price and volume signals predict the cross-section of forward returns in US large caps "
        "after costs? Does a combination of them survive purged cross-validation and a multiple-testing correction? "
        "The goal is an honest answer, not a large Sharpe ratio.")
    add("")
    add("## 2. Data and limitations")
    add("")
    add(f"- Daily adjusted prices and volume from yfinance, {dq['first_date']} to {dq['last_date']} "
        f"({dq['n_trading_days']:,} trading days).")
    add(f"- Universe: S&P 500, with point-in-time membership rebuilt by walking the index change log back from today's Wikipedia list. "
        f"{dq['n_historical_members']} tickers were members at some point. A stock is only traded while it is a member.")
    add(f"- **Survivorship bias.** {dq['n_members_no_data']} of {dq['n_historical_members']} historical members "
        f"({dq['n_members_no_data'] / dq['n_historical_members']:.1%}) have no data on yfinance. These are mostly delisted "
        f"or acquired names. The share of a year's members with no data ranges from "
        f"{surv['pct_members_no_data'].min():.1f}% to {surv['pct_members_no_data'].max():.1f}% "
        f"(worst year: {int(surv.loc[surv['pct_members_no_data'].idxmax(), 'year'])}, Figure 1). "
        f"Results are biased by this, most likely upward for anything that buys distressed stocks.")
    add(f"- The change log does not fit the rebuilt membership in {dq['n_membership_inconsistencies']} events "
        f"(renamed or recycled tickers). They are listed in `tables/membership_inconsistencies.csv`.")
    if dq.get("change_log_snapshot_date"):
        add(f"- Wikipedia no longer shows the change log on the live article. Membership history comes from: "
            f"{dq['change_log_source']}, up to {dq['change_log_snapshot_date']}. The "
            f"{dq['n_membership_events_approximated']} changes after that date are approximated: additions use the "
            f"'Date added' column, removals are dated at the last addition.")
    add(f"- Sectors are today's GICS sectors, not point-in-time. {dq['n_unknown_sector']} tickers that left the index "
        f"have no sector and are grouped as Unknown.")
    add(f"- Cleaning: {dq['n_extreme_returns']} one-day returns above {cfg['quality']['max_abs_return']:.0%} in absolute "
        f"value were flagged, of which {dq['n_split_repairs']} looked like unadjusted splits and were repaired. "
        f"{dq['n_zero_volume_days']:,} zero-volume days and {dq['n_missing_days_inside_history']:,} missing days were found. "
        f"Prices are never forward-filled.")
    add(f"- Liquidity filter, past data only: price at least ${cfg['liquidity']['min_price']:.0f} and "
        f"{cfg['liquidity']['window']}-day median dollar volume at least ${cfg['liquidity']['min_median_dollar_volume'] / 1e6:.0f}M. "
        f"It removes {dq['member_days_dropped_illiquid'] / dq['member_days']:.1%} of member-days. "
        f"On average {dq['avg_tradable_per_day']:.0f} stocks are tradable per day.")
    add(f"- Split: research set to {dq['research_end']}; final holdout from {dq['holdout_start']} "
        f"(the last {cfg['split']['holdout_months']} months). The loader cuts the holdout off unless an explicit flag is passed.")
    add("")
    add("![Figure 1](figures/fig1_survivorship.png)")
    add("")
    add("## 3. Signals")
    add("")
    add(f"Timing: a signal for day t uses data up to the close of t. The position is entered at the close of "
        f"t+{ENTRY_LAG}. The label is the return from close t+{ENTRY_LAG} to close t+{ENTRY_LAG}+h, demeaned across "
        f"stocks, with h = {h} days. Each signal is winsorized, ranked, mapped to z-scores, and neutralized against "
        f"sector dummies and market beta, per date. Signs were fixed in advance from the literature.")
    add("")
    add(f"Single-signal results on the research set, {meta['evaluation_start']} to {meta['evaluation_end']} "
        f"(t-statistics use Newey-West errors with {meta['nw_lags']} lags):")
    add("")
    show = sig[["mean_ic", "icir", "nw_tstat", "monotonicity", f"autocorr_{h}d", "daily_turnover", "net_sharpe"]].copy()
    show.columns = ["Mean IC", "ICIR", "NW t", "Quintile monotonicity", f"Autocorr {h}d", "Daily turnover", f"Net Sharpe ({cost} bps)"]
    show.index.name = "Signal"
    add(to_markdown(show, fmt={"Mean IC": "{:.4f}", "NW t": "{:.2f}", "Net Sharpe (%d bps)" % cost: "{:.2f}"}))
    add("")
    add("![Figure 2](figures/fig2_ic_by_signal.png)")
    add("")
    add("![Figure 3](figures/fig3_ic_decay.png)")
    add("")
    add("## 4. Validation method")
    add("")
    add(f"- **Purged K-fold** ({val['n_splits']} folds, split by date). A {h}-day label overlaps its neighbours, so "
        f"training dates within {h} days of a test fold are removed, plus a {val['embargo_days']}-day embargo after it.")
    add(f"- **CPCV** with {val['cpcv_groups']} groups and {val['cpcv_test_groups']} test groups: {sel['cpcv_splits']} "
        f"splits and {sel['cpcv_paths']} full backtest paths. This gives a distribution of out-of-sample Sharpe ratios.")
    add("- **Probabilistic Sharpe ratio (PSR)**: the probability that the true Sharpe is above a benchmark, allowing "
        "for sample length, skew and fat tails.")
    add(f"- **Deflated Sharpe ratio (DSR)**: PSR against the Sharpe that the best of N zero-skill trials would be expected "
        f"to show. Every configuration ever evaluated is logged in `trials.jsonl` ({st['n_trials_distinct']} distinct "
        f"configurations, {st['n_trial_records']} evaluations).")
    add("- **PBO**: how often the in-sample best trial falls below the median out of sample.")
    add(f"- **Holdout**: one frozen configuration, run once. A fitted model replaces equal weighting only if it beats "
        f"it in purged CV with a t-statistic of at least {sel['tstat_threshold']:.1f}. This rule was fixed in the config beforehand.")
    add("- All of this is implemented from scratch and covered by tests (lookahead, purge, timing, null, planted signal, "
        "PSR and DSR against hand-computed values, universe).")
    add("")
    add("## 5. Results")
    add("")
    add(f"**Combination models, purged CV, net of {cost} bps per side.** Best grid point per family:")
    add("")
    best = cv.loc[cv.groupby("family")["net_sharpe"].idxmax()].set_index("family")
    best = best.loc[[f for f in ["equal_weight", "ic_weighted", "ridge", "lightgbm"] if f in best.index]]
    tab = best[["params", "gross_sharpe", "net_sharpe", "net_ann_return", "net_max_drawdown", "daily_turnover", "break_even_bps"]].copy()
    tab = tab.join(cpcv[["split_mean", "split_std", "split_frac_positive"]])
    tab.columns = ["Params", "Gross Sharpe", "Net Sharpe", "Net ann. return", "Max drawdown", "Daily turnover",
                   "Break-even bps", "CPCV mean", "CPCV s.d.", "CPCV share > 0"]
    tab.index.name = "Model"
    add(to_markdown(tab, fmt={"Net ann. return": PCT, "Max drawdown": PCT, "Daily turnover": PCT, "Break-even bps": "{:.1f}",
                              "CPCV share > 0": "{:.0%}"}, default="{:.2f}"))
    add("")
    if sel["complex_beats_equal_weight"]:
        add(f"The best model in CV is {sel['best_cv_family']} (net Sharpe {sel['best_cv_net_sharpe']:.2f} against "
            f"{sel['equal_weight_net_sharpe']:.2f} for equal weight). The difference has a t-statistic of "
            f"{sel['tstat_best_vs_equal_weight']:.2f}, above the threshold, so it was frozen.")
    elif sel["best_cv_family"] == "equal_weight":
        add(f"**The complex models do not beat equal weighting.** Equal weight has the highest net Sharpe in CV "
            f"({sel['equal_weight_net_sharpe']:.2f}), so it was frozen.")
    else:
        add(f"**The complex models do not reliably beat equal weighting.** The best CV model is {sel['best_cv_family']} "
            f"(net Sharpe {sel['best_cv_net_sharpe']:.2f} against {sel['equal_weight_net_sharpe']:.2f} for equal weight), "
            f"but the difference has a t-statistic of only {sel['tstat_best_vs_equal_weight']:.2f}, below the threshold of "
            f"{sel['tstat_threshold']:.1f}. Equal weight was frozen.")
    add("")
    add("![Figure 4](figures/fig4_cv_cumulative.png)")
    add("")
    add("![Figure 5](figures/fig5_cpcv_sharpe.png)")
    add("")
    if fam in ("equal_weight",):
        add("Equal weighting fits nothing, so its CPCV paths are identical. Its spread across test splits shows "
            "variation across time periods only.")
        add("")
    add(f"**Frozen configuration ({fam}), research set versus holdout:**")
    add("")
    add(_headline_table(cfg))
    add("")
    add(f"**Costs.** Net Sharpe by cost per side: "
        + ", ".join(f"{int(c)} bps: {row['sharpe']:.2f}" for c, row in costs.iterrows())
        + f". Break-even cost is {chosen['break_even_bps']:.1f} bps per side.")
    add("")
    add(f"**Multiple testing.** PSR against zero is {st['psr_vs_zero']:.3f}. The trial Sharpe ratios imply an expected "
        f"maximum annualized Sharpe of {st['dsr_raw_n']['sr_star'] * 252 ** 0.5:.2f} under the null with raw N = "
        f"{st['n_trials_distinct']}, and the DSR is {st['dsr_raw_n']['dsr']:.3f}. The trials are correlated (average "
        f"correlation {st['effective_n']['avg_corr']:.2f}), so raw N overstates the number of independent bets. With "
        f"effective N = {st['effective_n']['n_eff_avg_corr']:.1f} (average-correlation estimate) the DSR is "
        f"{st['dsr_effective_n_avg_corr']['dsr']:.3f}; with effective N = {st['effective_n']['n_eff_eigen']:.1f} "
        f"(eigenvalue estimate) it is {st['dsr_effective_n_eigen']['dsr']:.3f}. "
        f"The two effective-N estimates differ a lot, so the DSR is best read as a range. It is also conservative: the "
        f"variance of trial Sharpe ratios includes real differences between signals, not only noise. "
        f"PBO is {st['pbo']['pbo']:.2f} over {st['pbo']['n_splits']} splits.")
    add("")
    add(f"**Robustness.** Equal weight at other horizons, net Sharpe: "
        + ", ".join(f"h = {int(k)}: {row['net_sharpe']:.2f}" for k, row in robust.iterrows())
        + f". Net Sharpe of the frozen model by year ranges from {by_year[fam].min():.2f} ({int(by_year[fam].idxmin())}) to "
        f"{by_year[fam].max():.2f} ({int(by_year[fam].idxmax())}); it is positive in {(by_year[fam] > 0).sum()} of {len(by_year)} years. "
        f"IC by year and by sector is in `tables/ic_by_year.csv` and `tables/ic_by_sector.csv`.")
    add("")
    if holdout:
        add(f"**Holdout.** One run, {holdout['holdout_start']} to {holdout['holdout_end']} "
            f"(holdout loads logged: {holdout_access_count(cfg)}). Net Sharpe {holdout['net']['sharpe']:.2f} against "
            f"{chosen['net_sharpe']:.2f} in CV. Mean daily IC of the combined score {holdout['ic']['mean_ic']:.4f} "
            f"(Newey-West t = {holdout['ic']['nw_tstat']:.2f}). PSR against zero {holdout['psr_vs_zero']:.3f}. "
            f"With {holdout['net']['n_days']} days, the standard error of an annualized Sharpe is about "
            f"{(252 / holdout['net']['n_days']) ** 0.5:.2f}, so the holdout can only confirm or reject large effects.")
        add("")
        add("![Figure 6](figures/fig6_holdout.png)")
    else:
        add("**Holdout.** Not run yet. `scripts/06_holdout.py` runs it once with the frozen configuration.")
    add("")
    add("## 6. What did not work")
    add("")
    weak = sig.index[sig["nw_tstat"].abs() < 2].tolist()
    wrong = sig.index[(sig["nw_tstat"] <= -2)].tolist()
    lossy = sig.index[sig["net_sharpe"] < 0].tolist()
    add(f"- {len(weak)} of {len(sig)} signals have an IC that is not significant at |t| < 2"
        + (f": {', '.join(weak)}." if weak else "."))
    add(f"- Signals with a significant IC of the opposite sign to the prior: {len(wrong)}"
        + (f" ({', '.join(wrong)}). The sign was not flipped after the fact." if wrong else "."))
    add(f"- {len(lossy)} of {len(sig)} single-signal portfolios lose money after {cost} bps per side"
        + (f": {', '.join(lossy)}." if lossy else "."))
    if not sel["complex_beats_equal_weight"]:
        add("- Ridge and LightGBM did not earn their complexity over an equal-weight average (table above).")
    dsr = st["dsr_raw_n"]["dsr"]
    add(f"- The deflated Sharpe ratio with raw N is {dsr:.3f}, "
        + ("above" if dsr >= 0.95 else "below") + " the usual 0.95 bar"
        + ("." if dsr >= 0.95 else ". After correcting for the number of trials, the result is not statistically convincing."))
    if holdout:
        gap = holdout["net"]["sharpe"] - chosen["net_sharpe"]
        add(f"- Holdout net Sharpe is {abs(gap):.2f} " + ("below" if gap < 0 else "above") + " the CV estimate. "
            "Nothing was tuned after seeing it.")
    add("")
    add("## 7. Next steps")
    add("")
    add("- Replace yfinance with a survivorship-free source (CRSP or similar) to remove the main data limitation.")
    add("- Use point-in-time sectors and an explicit risk model instead of sector dummies plus one beta.")
    add("- Model costs as a function of spread and volatility, and add a turnover penalty to the portfolio step.")
    add("- Test on other universes (mid caps, Europe) as a true out-of-sample check of the same frozen pipeline.")
    add("")
    (rd / "writeup.md").write_text("\n".join(L))

    block = ["<!-- RESULTS:START -->", f"Frozen configuration: **{fam}** {sel['chosen_params'] or ''}. "
             f"Costs: {cost} bps per side. Distinct trials logged: {st['n_trials_distinct']}.", "", _headline_table(cfg), "",
             f"PSR vs 0 (research): {st['psr_vs_zero']:.3f} | DSR raw N: {st['dsr_raw_n']['dsr']:.3f} | "
             f"DSR effective N: {st['dsr_effective_n_avg_corr']['dsr']:.3f} | PBO: {st['pbo']['pbo']:.2f}"
             + (f" | PSR vs 0 (holdout): {holdout['psr_vs_zero']:.3f}" if holdout else " | holdout not run yet"),
             "<!-- RESULTS:END -->"]
    (rd / "headline.md").write_text("\n".join(block))
    readme = ROOT / "README.md"
    if readme.exists() and not dq.get("synthetic"):
        text = readme.read_text()
        a, b = text.find("<!-- RESULTS:START -->"), text.find("<!-- RESULTS:END -->")
        if a >= 0 and b > a:
            readme.write_text(text[:a] + "\n".join(block) + text[b + len("<!-- RESULTS:END -->"):])
